"""
JSON to PDF converter for ActChain reports.

The PDF is the executive artifact (design R15): a concise, decision-oriented
rendering of the consolidated JSON report. It carries a summary page
(severity totals, scanners used, AI status, malicious banner, pinning-gate
verdict), full detail for malicious/critical/high findings, capped compact
lists for medium/low findings, and a capped dependency appendix. The JSON
report remains the complete record.

``fpdf2`` is an optional dependency (install the ``pdf`` extra); it is
imported lazily so the rest of ActChain works without it. All finding and
dependency text is attacker-influenced and passes through ``_safe`` before
it reaches the document.
"""

import json
import logging
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from ..utils.file_utils import FileUtils
from ..utils.security_utils import SecurityUtils

logger = logging.getLogger('actchain.reports.pdf_converter')

# Length caps (in characters) for attacker-influenced text, applied by _safe.
TITLE_LIMIT = 200
DESCRIPTION_LIMIT = 800
RECOMMENDATION_LIMIT = 400
RATIONALE_LIMIT = 300
PATH_LIMIT = 150
NAME_LIMIT = 100

# Layout caps (R15): the PDF stays concise; the JSON report holds everything.
MAX_FINDINGS_PER_MINOR_SEVERITY = 25  # applies to medium and to low
MAX_DEPENDENCY_ROWS = 50
MAX_GATE_REASONS = 5

_SEVERITIES = ('critical', 'high', 'medium', 'low')

# Severity accent colors (RGB), matching the HTML report palette.
_SEVERITY_COLORS = {
    'critical': (229, 62, 62),
    'high': (221, 107, 32),
    'medium': (214, 158, 46),
    'low': (56, 161, 105),
}


def _import_fpdf() -> Any:
    """Return the ``FPDF`` class from the optional ``fpdf2`` package.

    Kept as a module-level function so tests can simulate a missing
    dependency by monkeypatching it to raise ``ImportError``.

    Returns:
        The ``fpdf.FPDF`` class.

    Raises:
        ImportError: If ``fpdf2`` is not installed.
    """
    from fpdf import FPDF
    return FPDF


def _safe(text: Any, limit: int) -> str:
    """Sanitize one attacker-influenced value for PDF rendering.

    Pipeline: ``str()`` -> strip control/bidi/zero-width characters ->
    truncate to ``limit`` characters -> force latin-1 (the built-in
    Helvetica font cannot encode anything else; unsupported characters
    become ``?`` instead of crashing generation).

    Args:
        text: Any value destined for the PDF.
        limit: Maximum number of characters to keep.

    Returns:
        A latin-1-safe string of at most ``limit`` characters.
    """
    cleaned = SecurityUtils.strip_control_chars(str(text))
    cleaned = cleaned[:limit]
    return cleaned.encode('latin-1', 'replace').decode('latin-1')


def _as_dict(value: Any) -> Dict[str, Any]:
    """Return ``value`` if it is a dict, else an empty dict."""
    return value if isinstance(value, dict) else {}


def _as_list(value: Any) -> List[Any]:
    """Return ``value`` if it is a list, else an empty list."""
    return value if isinstance(value, list) else []


class PDFReportGenerator:
    """Generates executive PDF reports from consolidated JSON data.

    Layout (design R15): a summary page (title, scan metadata, severity
    totals, scanners, AI status, malicious banner, pinning-gate verdict),
    full detail for malicious/critical/high findings, capped compact lists
    for medium/low findings, and a capped dependency appendix. Every page
    carries a "Generated by ActChain" footer with the page number.

    Test seam: every logical line of text written into the PDF body is also
    appended to ``self._rendered_lines`` (exposed through the
    ``rendered_lines`` property), so tests can assert on report content
    without parsing PDF binary output. Page footers are not part of the
    seam.
    """

    def __init__(self) -> None:
        """Initialize the PDF report generator."""
        self._rendered_lines: List[str] = []
        self._pdf: Any = None

    @property
    def rendered_lines(self) -> List[str]:
        """Logical text lines written during the last generation (test seam)."""
        return list(self._rendered_lines)

    def convert_json_to_pdf(self, json_path: str) -> Optional[str]:
        """Convert a consolidated JSON report to PDF format.

        Mirrors ``HTMLReportGenerator.convert_json_to_html``: reads the
        consolidated JSON report and writes the PDF next to it.

        Args:
            json_path: Path to the consolidated JSON report.

        Returns:
            Path to the generated PDF report, or None on failure (a PDF
            failure must never break the scan).
        """
        try:
            # Determine output path
            pdf_path = str(Path(json_path).with_suffix('.pdf'))

            # Load JSON data
            json_content = FileUtils.safe_read_file(json_path)
            if not json_content:
                logger.error(f"Failed to read JSON report: {json_path}")
                return None

            # Parse JSON
            try:
                data = json.loads(json_content)
            except json.JSONDecodeError as e:
                logger.error(f"Invalid JSON in {json_path}: {e}")
                return None

            if not isinstance(data, dict):
                logger.error(f"Unexpected JSON structure in {json_path}: expected an object")
                return None

            return self.generate_pdf(data, pdf_path)

        except Exception as e:
            logger.error(f"Error converting JSON to PDF: {e}")
            return None

    def generate_pdf(self, data: Dict[str, Any], pdf_path: str) -> Optional[str]:
        """Generate a PDF report file from consolidated report data.

        Args:
            data: Parsed consolidated report (version 1.1 shape; every field
                may be missing or partial).
            pdf_path: Destination file path for the PDF.

        Returns:
            ``pdf_path`` on success, or None on any failure.
        """
        self._rendered_lines = []

        try:
            fpdf_class = _import_fpdf()
        except ImportError:
            logger.error('PDF generation requires the "pdf" extra: pip install "actchain[pdf]"')
            return None

        try:
            self._pdf = self._create_document(fpdf_class)
            self._pdf.add_page()
            self._render_summary_page(data)
            self._pdf.add_page()
            self._render_findings_sections(data)
            self._pdf.add_page()
            self._render_dependency_appendix(data)
            self._pdf.output(pdf_path)
            logger.info(f"Generated PDF report: {pdf_path}")
            return pdf_path
        except Exception as e:
            logger.error(f"Error generating PDF report: {e}")
            return None
        finally:
            self._pdf = None

    # ------------------------------------------------------------------
    # Section rendering
    # ------------------------------------------------------------------

    def _render_summary_page(self, data: Dict[str, Any]) -> None:
        """Render the executive summary page.

        Args:
            data: Parsed consolidated report.
        """
        meta = _as_dict(data.get('meta'))
        workflow = _as_dict(data.get('workflow'))
        statistics = _as_dict(data.get('statistics'))
        findings = [f for f in _as_list(data.get('findings')) if isinstance(f, dict)]

        self._write_line('ActChain Security Report', size=20, style='B', height=10.0)

        workflow_name = _safe(workflow.get('name') or 'Unknown', NAME_LIMIT)
        scan_id = _safe(meta.get('scan_id') or 'Unknown', NAME_LIMIT)
        timestamp = _safe(meta.get('timestamp') or datetime.now().isoformat(), NAME_LIMIT)
        self._write_line(f'Workflow: {workflow_name}', size=11)
        self._write_line(f'Scan ID: {scan_id}', size=11)
        self._write_line(f'Date: {timestamp}', size=11)

        self._render_severity_table(statistics)
        self._render_scanners_and_ai(statistics, data)
        self._render_malicious_banner(findings)
        self._render_gate_verdict(data)

    def _render_severity_table(self, statistics: Dict[str, Any]) -> None:
        """Render the severity totals table.

        Args:
            statistics: The report's ``statistics`` section.
        """
        severity_counts = _as_dict(statistics.get('severity_counts'))
        self._write_heading('Findings by Severity', space_before=5.0)
        self._pdf.set_fill_color(240, 242, 245)
        self._write_table_row([('Severity', 50.0), ('Count', 30.0)], style='B', fill=True)
        for severity in _SEVERITIES:
            count = _safe(severity_counts.get(severity, 0), 12)
            self._write_table_row([(severity.capitalize(), 50.0), (count, 30.0)])
        total = _safe(severity_counts.get('total', 0), 12)
        self._write_table_row([('Total', 50.0), (total, 30.0)], style='B')

    def _render_scanners_and_ai(self, statistics: Dict[str, Any], data: Dict[str, Any]) -> None:
        """Render the scanners-used list and the AI status line.

        Args:
            statistics: The report's ``statistics`` section.
            data: Parsed consolidated report (for the ``ai`` section).
        """
        scanner_counts = _as_dict(statistics.get('scanner_counts'))
        self._write_heading('Scanners', space_before=5.0)
        if scanner_counts:
            for scanner, count in scanner_counts.items():
                name = _safe(scanner, NAME_LIMIT)
                findings_count = _safe(count, 12)
                self._write_line(f'- {name}: {findings_count} finding(s)', indent=2.0)
        else:
            self._write_line('- none recorded', indent=2.0)

        ai = _as_dict(data.get('ai'))
        self._pdf.ln(2)
        if ai.get('enabled'):
            model = _safe(ai.get('model') or 'unknown model', NAME_LIMIT)
            calls = _safe(ai.get('calls', 0), 12)
            self._write_line(f'AI analysis: {model}, {calls} calls')
        else:
            self._write_line('AI analysis: not enabled')

    def _render_malicious_banner(self, findings: List[Dict[str, Any]]) -> None:
        """Render the prominent malicious-findings banner when needed.

        Args:
            findings: All findings from the report (dict entries only).
        """
        malicious = self._malicious_findings(findings)
        if not malicious:
            return

        pdf = self._pdf
        pdf.ln(5)
        pdf.set_fill_color(185, 28, 28)
        pdf.set_text_color(255, 255, 255)
        self._write_line(f'MALICIOUS BEHAVIOR DETECTED - {len(malicious)} finding(s)',
                         size=13, style='B', height=9.0, fill=True)
        pdf.set_fill_color(248, 215, 218)
        pdf.set_text_color(90, 10, 10)
        for finding in malicious:
            title = _safe(finding.get('title') or 'Untitled finding', TITLE_LIMIT)
            path = _safe(_as_dict(finding.get('location')).get('path') or 'unknown location', PATH_LIMIT)
            self._write_line(f'- {title} ({path})', height=6.0, fill=True)
        pdf.set_text_color(0, 0, 0)

    def _render_gate_verdict(self, data: Dict[str, Any]) -> None:
        """Render the pinning policy gate verdict when it was evaluated.

        Args:
            data: Parsed consolidated report (for the ``gate`` section).
        """
        gate = _as_dict(data.get('gate'))
        if not gate.get('evaluated'):
            return

        pdf = self._pdf
        threshold = _safe(gate.get('threshold') or 'unknown', NAME_LIMIT)
        self._write_heading('Pinning Gate', space_before=5.0)

        if gate.get('passed'):
            pdf.set_text_color(*_SEVERITY_COLORS['low'])
            self._write_line(f'PASSED (threshold: {threshold})', size=11, style='B')
            pdf.set_text_color(0, 0, 0)
            self._render_pin_plan_summary(gate)
            return

        blocking = gate.get('blocking_findings_count')
        suffix = f' - {_safe(blocking, 12)} blocking finding(s)' if isinstance(blocking, int) else ''
        pdf.set_text_color(*_SEVERITY_COLORS['critical'])
        self._write_line(f'BLOCKED (threshold: {threshold}){suffix}', size=11, style='B')
        pdf.set_text_color(0, 0, 0)

        reasons = _as_list(gate.get('reasons'))
        shown = reasons[:MAX_GATE_REASONS]
        for reason in shown:
            self._write_line(f'- {_safe(reason, TITLE_LIMIT)}', indent=2.0)
        hidden = len(reasons) - len(shown)
        if hidden > 0:
            self._write_line(f'... and {hidden} more reason(s) - see the JSON report.',
                             style='I', indent=2.0)
        self._render_pin_plan_summary(gate)

    def _render_pin_plan_summary(self, gate: Dict[str, Any]) -> None:
        """One line summarizing the computed pin plan (details in the JSON)."""
        plan = _as_dict(gate.get('pin_plan'))
        if not plan:
            return
        entries = plan.get('entries_total')
        skipped = plan.get('skipped_total')
        if not isinstance(entries, int):
            return
        skipped_text = f', {skipped} skipped' if isinstance(skipped, int) and skipped else ''
        self._write_line(
            f'Pin plan: {entries} reference(s) to pin{skipped_text} - see the JSON report.',
            indent=2.0)

    def _render_findings_sections(self, data: Dict[str, Any]) -> None:
        """Render all findings: malicious first, then by descending severity.

        Malicious, critical and high findings get full detail; medium and
        low findings get compact lines capped at
        ``MAX_FINDINGS_PER_MINOR_SEVERITY`` each.

        Args:
            data: Parsed consolidated report.
        """
        findings = [f for f in _as_list(data.get('findings')) if isinstance(f, dict)]
        self._write_heading('Findings', size=16, space_before=0.0)

        if not findings:
            self._write_line('No security findings.', size=11)
            return

        malicious = self._malicious_findings(findings)
        groups = self._group_by_severity([f for f in findings if not f.get('malicious')])

        if malicious:
            self._write_heading(f'Malicious Findings ({len(malicious)})',
                                color=_SEVERITY_COLORS['critical'])
            for finding in malicious:
                self._render_finding_detail(finding)

        for severity in ('critical', 'high'):
            group = groups[severity]
            if not group:
                continue
            self._write_heading(f'{severity.capitalize()} Severity ({len(group)})',
                                color=_SEVERITY_COLORS[severity])
            for finding in group:
                self._render_finding_detail(finding)

        for severity in ('medium', 'low'):
            group = groups[severity]
            if not group:
                continue
            self._write_heading(f'{severity.capitalize()} Severity ({len(group)})',
                                color=_SEVERITY_COLORS[severity])
            shown = group[:MAX_FINDINGS_PER_MINOR_SEVERITY]
            for finding in shown:
                self._render_finding_compact(finding)
            hidden = len(group) - len(shown)
            if hidden > 0:
                self._write_line(f'... and {hidden} more {severity} findings - see the JSON report.',
                                 style='I', indent=2.0)

    def _render_finding_detail(self, finding: Dict[str, Any]) -> None:
        """Render one finding with full detail (malicious/critical/high).

        Args:
            finding: One finding dict from the report.
        """
        pdf = self._pdf
        severity = str(finding.get('severity', 'low')).lower()
        if severity not in _SEVERITIES:
            severity = 'low'
        title = _safe(finding.get('title') or 'Untitled finding', TITLE_LIMIT)

        pdf.ln(2)
        pdf.set_text_color(*_SEVERITY_COLORS[severity])
        self._write_line(f'[{severity.upper()}] {title}', size=11, style='B', height=6.0)
        pdf.set_text_color(0, 0, 0)

        location_text = self._format_location(finding)
        if location_text:
            self._write_line(f'Location: {location_text}', size=9, indent=2.0)

        scanner = _safe(finding.get('source_scanner') or 'unknown', NAME_LIMIT)
        self._write_line(f'Scanner: {scanner}', size=9, indent=2.0)

        ai_triage = _as_dict(finding.get('ai_triage'))
        if ai_triage:
            verdict = _safe(ai_triage.get('verdict') or 'unknown', NAME_LIMIT)
            rationale = _safe(ai_triage.get('rationale') or '', RATIONALE_LIMIT)
            triage_text = f'AI triage: {verdict}'
            if rationale:
                triage_text = f'{triage_text} - {rationale}'
            self._write_line(triage_text, size=9, style='I', indent=2.0)

        description = _safe(finding.get('description') or '', DESCRIPTION_LIMIT)
        if description:
            self._write_line(description, indent=2.0)

        recommendation = _safe(finding.get('recommendation') or '', RECOMMENDATION_LIMIT)
        if recommendation:
            self._write_line(f'Recommendation: {recommendation}', indent=2.0)

    def _render_finding_compact(self, finding: Dict[str, Any]) -> None:
        """Render one finding as a single compact line (medium/low).

        Args:
            finding: One finding dict from the report.
        """
        title = _safe(finding.get('title') or 'Untitled finding', TITLE_LIMIT)
        scanner = _safe(finding.get('source_scanner') or 'unknown', NAME_LIMIT)
        text = f'- {title}'
        location_text = self._format_location(finding)
        if location_text:
            text = f'{text} [{location_text}]'
        self._write_line(f'{text} ({scanner})', size=9, indent=2.0)

    def _render_dependency_appendix(self, data: Dict[str, Any]) -> None:
        """Render the dependency appendix table, capped at 50 rows.

        Args:
            data: Parsed consolidated report.
        """
        dependencies = [d for d in _as_list(data.get('dependencies')) if isinstance(d, dict)]
        self._write_heading(f'Appendix: Dependencies ({len(dependencies)})', size=16, space_before=0.0)

        if not dependencies:
            self._write_line('No dependencies recorded.', size=11)
            return

        pdf = self._pdf
        pdf.set_fill_color(240, 242, 245)
        widths = (92.0, 38.0, 20.0, 25.0)
        self._write_table_row(
            [('Name', widths[0]), ('Type', widths[1]), ('Depth', widths[2]), ('Findings', widths[3])],
            style='B', fill=True)

        pdf.set_font('helvetica', '', 8)
        shown = dependencies[:MAX_DEPENDENCY_ROWS]
        for dep in shown:
            name = self._fit_cell(_safe(dep.get('name') or 'unknown', NAME_LIMIT), widths[0] - 2.0)
            dep_type = self._fit_cell(_safe(dep.get('type') or 'unknown', NAME_LIMIT), widths[1] - 2.0)
            depth = _safe(dep.get('depth', 0), 8)
            findings_count = _safe(dep.get('findings_count', 0), 8)
            self._write_table_row(
                [(name, widths[0]), (dep_type, widths[1]), (depth, widths[2]), (findings_count, widths[3])],
                size=8)

        hidden = len(dependencies) - len(shown)
        if hidden > 0:
            self._write_line(f'... and {hidden} more dependencies - see the JSON report.', style='I')

    # ------------------------------------------------------------------
    # Low-level drawing helpers (every helper records what it writes)
    # ------------------------------------------------------------------

    def _create_document(self, fpdf_class: Any) -> Any:
        """Create a configured FPDF document with the ActChain footer.

        Args:
            fpdf_class: The lazily imported ``fpdf.FPDF`` class.

        Returns:
            A ready-to-use FPDF instance (A4 portrait, millimetre units).
        """

        class _ActChainPDF(fpdf_class):  # type: ignore[misc, valid-type]
            """FPDF subclass adding the standard ActChain page footer."""

            def footer(self) -> None:
                self.set_y(-15)
                self.set_font('helvetica', 'I', 8)
                self.set_text_color(120, 120, 120)
                self.cell(0, 10, f'Generated by ActChain - Page {self.page_no()}', align='C')

        pdf = _ActChainPDF(orientation='portrait', unit='mm', format='A4')
        pdf.set_title('ActChain Security Report')
        pdf.set_creator('ActChain')
        pdf.set_margins(15, 15, 15)
        pdf.set_auto_page_break(auto=True, margin=20)
        return pdf

    def _write_line(self, text: str, size: float = 10, style: str = '',
                    height: float = 5.0, indent: float = 0.0, fill: bool = False) -> None:
        """Record one logical line and draw it as wrapped PDF text.

        Args:
            text: Already-sanitized line content.
            size: Font size in points.
            style: Font style ('' regular, 'B' bold, 'I' italic).
            height: Line height in millimetres.
            indent: Extra left indent in millimetres.
            fill: Whether to paint the current fill color behind the text.
        """
        self._rendered_lines.append(text)
        pdf = self._pdf
        pdf.set_font('helvetica', style, size)
        if indent:
            pdf.set_x(pdf.l_margin + indent)
        pdf.multi_cell(0, height, text, align='L', fill=fill, new_x='LMARGIN', new_y='NEXT')

    def _write_heading(self, text: str, size: float = 13,
                       color: Optional[Tuple[int, int, int]] = None,
                       space_before: float = 3.0) -> None:
        """Record and draw a bold section heading.

        Args:
            text: Heading text (already sanitized where dynamic).
            size: Font size in points.
            color: Optional RGB text color for the heading.
            space_before: Vertical space in millimetres before the heading.
        """
        pdf = self._pdf
        if space_before:
            pdf.ln(space_before)
        if color:
            pdf.set_text_color(*color)
        self._write_line(text, size=size, style='B', height=7.0)
        pdf.set_text_color(0, 0, 0)

    def _write_table_row(self, cells: Sequence[Tuple[str, float]], style: str = '',
                         size: float = 9, fill: bool = False) -> None:
        """Record and draw one bordered table row.

        Args:
            cells: Sequence of ``(text, width-in-mm)`` pairs.
            style: Font style for the whole row.
            size: Font size in points.
            fill: Whether to paint the current fill color behind the cells.
        """
        self._rendered_lines.append(' | '.join(text for text, _ in cells))
        pdf = self._pdf
        pdf.set_font('helvetica', style, size)
        for index, (text, width) in enumerate(cells):
            last = index == len(cells) - 1
            pdf.cell(width, 6, text, border=1, fill=fill,
                     new_x='LMARGIN' if last else 'RIGHT',
                     new_y='NEXT' if last else 'TOP')

    def _fit_cell(self, text: str, max_width: float) -> str:
        """Shorten ``text`` with an ellipsis until it fits ``max_width``.

        Assumes the measuring font is already selected on the document.
        This is a layout concern only; sanitization happens in ``_safe``.

        Args:
            text: Sanitized cell text.
            max_width: Available width in millimetres.

        Returns:
            Text that fits the cell, ellipsized when necessary.
        """
        pdf = self._pdf
        if pdf.get_string_width(text) <= max_width:
            return text
        while text and pdf.get_string_width(f'{text}...') > max_width:
            text = text[:-1]
        return f'{text}...'

    # ------------------------------------------------------------------
    # Data helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _malicious_findings(findings: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Return the findings flagged ``malicious``, in input order."""
        return [finding for finding in findings if finding.get('malicious')]

    @staticmethod
    def _group_by_severity(findings: List[Dict[str, Any]]) -> Dict[str, List[Dict[str, Any]]]:
        """Group findings by severity level, treating unknown values as low."""
        groups: Dict[str, List[Dict[str, Any]]] = {severity: [] for severity in _SEVERITIES}
        for finding in findings:
            severity = str(finding.get('severity', 'low')).lower()
            if severity not in groups:
                # Never silently drop a finding with an unexpected severity
                # string; show it with the lowest severity instead.
                severity = 'low'
            groups[severity].append(finding)
        return groups

    @staticmethod
    def _format_location(finding: Dict[str, Any]) -> str:
        """Format a finding's location as ``path:line``.

        Args:
            finding: One finding dict from the report.

        Returns:
            ``path:line`` (or just ``path`` without a line number), or an
            empty string when no path is known.
        """
        location = _as_dict(finding.get('location'))
        path = _safe(location.get('path') or '', PATH_LIMIT)
        if not path:
            return ''
        line_value = location.get('line')
        if line_value is None:
            return path
        return f'{path}:{_safe(line_value, 12)}'


def convert_json_to_pdf(json_path: str) -> Optional[str]:
    """
    Convenience function to convert JSON report to PDF.

    Args:
        json_path: Path to the JSON report

    Returns:
        Path to the generated PDF report or None if failed
    """
    generator = PDFReportGenerator()
    return generator.convert_json_to_pdf(json_path)
