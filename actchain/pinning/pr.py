def _to_pr_error(exc: GithubException, doing: str) -> PinningPRError:
    """Map a GithubException to a PinningPRError with a safe message.

    The message includes the HTTP status and the API-provided message (run
    through secret redaction and control-character stripping) but never any
    token material. 403/404 responses get a permissions hint.

    Args:
        exc: The PyGithub exception being mapped.
        doing: Short description of the operation that failed.

    Returns:
        The PinningPRError to raise.
    """
    api_message = ''
    data = getattr(exc, 'data', None)
    if isinstance(data, dict):
        api_message = str(data.get('message') or '')
    api_message = SecurityUtils.strip_control_chars(
        SecurityUtils.sanitize_for_log(api_message), keep_newlines=False)
    status = getattr(exc, 'status', 'unknown')
    message = f'GitHub API error while {doing} (status {status}): {api_message or "no details provided"}'
    if status in (403, 404):
        message += f' — {_PERMISSIONS_HINT}'
    return PinningPRError(message)


def _verify_base_contents(repo: Any, plan: PinPlan, base_sha: str) -> None:
    """Verify the changed files are still what the scan saw (TOCTOU guard).

    Each file to be rewritten is fetched AT the recorded base commit and
    compared byte-for-byte with the scan-time original in
    ``plan.base_contents``. Any mismatch — including a file that is missing,
    undecodable, or has no recorded original — aborts before any blob,
    branch or PR is created: committing scan-time contents onto a head that
    changed meanwhile would silently revert the interim change.

    Args:
        repo: PyGithub Repository of the scanned repo.
        plan: Pin plan holding new_contents and their scan-time originals.
        base_sha: SHA of the recorded default-branch head commit.

    Raises:
        PinningPRError: When any file differs from its scanned content or
            the verification fetch fails.
    """
    for path in sorted(plan.new_contents):
        expected = plan.base_contents.get(path)
        if expected is None:
            raise PinningPRError(_FILES_CHANGED_MESSAGE)

        try:
            content_file = repo.get_contents(path, ref=base_sha)
            raw = content_file.content
            if not raw or getattr(content_file, 'encoding', '') == 'none':
                raw = repo.get_git_blob(content_file.sha).content
            current = base64.b64decode(raw).decode('utf-8')
        except GithubException as exc:
            if getattr(exc, 'status', None) == 404:
                # File deleted/renamed since the scan: that IS a change.
                raise PinningPRError(_FILES_CHANGED_MESSAGE) from exc
            raise _to_pr_error(exc, 'verifying workflow files at the base commit') from exc
        except (ValueError, UnicodeDecodeError) as exc:
            # No longer the UTF-8 text we scanned — treat as changed.
            raise PinningPRError(_FILES_CHANGED_MESSAGE) from exc

        if current != expected:
            raise PinningPRError(_FILES_CHANGED_MESSAGE)


def _create_branch(repo: Any, commit_sha: str) -> str:
    """Create a fresh ``actchain/pin-actions-*`` branch at the given commit.

    Never updates or force-pushes an existing ref: when the timestamped name
    is taken (HTTP 422), suffixes ``-2`` through ``-5`` are tried before
    giving up.

    Args:
        repo: PyGithub Repository of the scanned repo.
        commit_sha: SHA of the pinning commit the branch must point at.

    Returns:
        The created branch name.

    Raises:
        PinningPRError: When no unique branch name could be created or the
            API refused the ref creation.
    """
    timestamp = datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')
    base_name = f'actchain/pin-actions-{timestamp}'
    candidates = [base_name] + [f'{base_name}-{i}' for i in range(2, 6)]

    for candidate in candidates:
        try:
            repo.create_git_ref(f'refs/heads/{candidate}', commit_sha)
            return candidate
        except GithubException as exc:
            if getattr(exc, 'status', None) == 422:
                continue  # branch already exists — try the next suffix
            raise _to_pr_error(exc, 'creating the pinning branch') from exc

    raise PinningPRError(
        f'could not create a unique branch ({base_name} and suffixes -2..-5 already exist)'
    )


def create_pinning_pr(github_client: Any, plan: PinPlan, title: str, body: str) -> str:
    """Open the pinning pull request on the scanned repository.

    A single commit containing every rewritten workflow file is built with
    the Git Data API on top of the recorded default-branch head (R8 TOCTOU:
    the base is captured once, every changed file is verified to still match
    its scan-time content at that base, and every object is created from
    it), a new branch is created for it, and a PR is opened against the
    default branch.

    Args:
        github_client: Connected GitHubClient; its ``repo`` attribute is the
            authenticated PyGithub Repository of the scanned repo.
        plan: Pin plan whose ``new_contents`` holds the rewritten files.
        title: Pull request title.
        body: Pull request body (already rendered and sanitized).

    Returns:
        The HTML URL of the created pull request.

    Raises:
        PinningPRError: When the plan has no file changes, a changed file no
            longer matches its scan-time content, or any GitHub API call
            fails.
    """
    if not plan.new_contents:
        raise PinningPRError('the pin plan contains no file changes — nothing to commit')

    repo = github_client.repo

    try:
        default_branch = repo.default_branch
        base_sha = repo.get_git_ref(f'heads/{default_branch}').object.sha
        base_commit = repo.get_git_commit(base_sha)
    except GithubException as exc:
        raise _to_pr_error(exc, 'resolving the default branch head') from exc

    _verify_base_contents(repo, plan, base_sha)

    try:
        elements = []
        for path, new_content in sorted(plan.new_contents.items()):
            blob = repo.create_git_blob(new_content, 'utf-8')
            elements.append(InputGitTreeElement(path=path, mode='100644', type='blob', sha=blob.sha))

        base_tree = repo.get_git_tree(base_commit.tree.sha)
        new_tree = repo.create_git_tree(elements, base_tree)
        commit = repo.create_git_commit(_COMMIT_MESSAGE, new_tree, [base_commit])
    except GithubException as exc:
        raise _to_pr_error(exc, 'preparing the pinning commit') from exc

    branch = _create_branch(repo, commit.sha)

    try:
        pr = repo.create_pull(base=default_branch, head=branch, title=title, body=body)
    except GithubException as exc:
        raise _to_pr_error(exc, 'opening the pull request') from exc

    return pr.html_url
