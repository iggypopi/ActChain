"""
Pinning pull request: safe PR body rendering and branch/commit/PR creation.

PR body safety (R9): no raw workflow line content ever appears in the body.
Every dynamic ref/SHA cell is validated against the strict ref grammar (or
the full-SHA pattern) and anything that fails is excluded and counted; all
dynamic values render inside backtick code spans, which neutralizes
@mentions, #issue keywords and links, and are length-capped.

PR creation (R8): a branch is created from the recorded default-branch head
SHA via the Git Data API (blobs -> tree -> single commit), never force-pushed
and never updating an existing ref; a taken branch name gets a ``-2``..``-5``
suffix before giving up.
"""

import base64
import re
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from github import GithubException, InputGitTreeElement

from .. import __version__
from ..core.refs import parse_action_ref
from ..pipeline.context import GateResult, PinPlan, PinPlanEntry
from ..utils.security_utils import SecurityUtils

_FULL_SHA_RE = re.compile(r'^[0-9a-f]{40}$')

_MAX_TABLE_ROWS = 100
_MAX_SKIPPED_ROWS = 100
_MAX_REF_LEN = 255   # validation bound for base/ref cell values
_MAX_TEXT_LEN = 180  # display cap for paths and other sanitized values

_LOCKFILE_DOC_URL = (
    'https://docs.github.com/en/actions/concepts/security/workflow-dependency-lockfiles'
)

_COMMIT_MESSAGE = 'Pin GitHub Actions to commit SHAs\n\nGenerated by ActChain.'

_PERMISSIONS_HINT = (
    'the token needs contents:write and pull-requests:write permissions on the repository'
)

_FILES_CHANGED_MESSAGE = 'workflow files changed since the scan — re-run the scan'

_SEVERITY_ORDER = ('critical', 'high', 'medium', 'low')


class PinningPRError(Exception):
    """Raised when the pinning pull request cannot be created."""


# ----------------------------------------------------------------------
# PR body rendering
# ----------------------------------------------------------------------

def _code_span(value: Any, max_length: int = _MAX_TEXT_LEN) -> str:
    """Render a dynamic value as a sanitized, length-capped code span.

    Backticks and pipes are removed so the value can never escape the code
    span or the enclosing table cell; control characters are stripped.

    Args:
        value: Dynamic value to render.
        max_length: Maximum rendered length before truncation.

    Returns:
        The value wrapped in backticks, safe for a markdown table cell.
    """
    text = SecurityUtils.strip_control_chars(str(value), keep_newlines=False)
    text = text.replace('`', '').replace('|', '')
    if len(text) > max_length:
        text = text[:max_length] + '...'
    return f'`{text}`' if text else '`-`'


def _entry_is_valid(entry: PinPlanEntry) -> bool:
    """Validate one pin table entry against the strict ref grammar (R9).

    ``action_base`` plus ``old_ref`` must round-trip through
    :func:`parse_action_ref` (base and ref reproduced exactly) and
    ``new_sha`` must be a full 40-hex SHA.

    Args:
        entry: The planned pin to validate.

    Returns:
        True when every dynamic cell of the entry is safe to render.
    """
    base = entry.action_base
    old_ref = entry.old_ref
    if not isinstance(base, str) or not isinstance(old_ref, str) or not isinstance(entry.new_sha, str):
        return False
    if len(base) > _MAX_REF_LEN or len(old_ref) > _MAX_REF_LEN:
        return False
    parsed = parse_action_ref(f'{base}@{old_ref}')
    if parsed is None or parsed.base != base or parsed.ref != old_ref:
        return False
    return bool(_FULL_SHA_RE.match(entry.new_sha))


def _int_count(counts: Dict[str, Any], key: str) -> int:
    """Read one severity counter defensively.

    Args:
        counts: The ``severity_counts`` mapping from scan statistics.
        key: Severity name (or 'total').

    Returns:
        The integer count, or 0 when missing/invalid.
    """
    try:
        return int(counts.get(key, 0))
    except (TypeError, ValueError):
        return 0


def render_pr_body(
    plan: PinPlan,
    gate: Optional[GateResult],
    stats: Dict[str, Any],
    repo_name: str,
    scanner_names: List[str],
    ai_enabled: bool,
) -> str:
    """Render the pull request body markdown for a pin plan.

    All dynamic values are validated and/or sanitized and rendered inside
    code spans; raw workflow line content never appears (R9).

    Args:
        plan: The pin plan produced by the planner.
        gate: Policy gate result (threshold and verdict), or None.
        stats: Scan statistics; ``stats["severity_counts"]`` holds the
            finding totals by severity.
        repo_name: Scanned repository in ``owner/repo`` form.
        scanner_names: Names of the scanners that ran.
        ai_enabled: Whether AI analysis ran for this scan.

    Returns:
        The PR body as a markdown string.
    """
    lines: List[str] = []

    # 1. Heading + rationale.
    lines.append('# Pin GitHub Actions to commit SHAs')
    lines.append('')
    lines.append(
        'Tag and branch references are mutable: the code they point to can change at any '
        'time after a review, while a commit SHA is immutable. This pull request pins each '
        'action to the exact commit SHA whose content this ActChain scan fetched and '
        'verified, so the workflows keep running precisely the code that was scanned.'
    )
    lines.append('')

    # 2. Scan summary.
    severity_counts = stats.get('severity_counts') if isinstance(stats, dict) else {}
    if not isinstance(severity_counts, dict):
        severity_counts = {}
    totals = ', '.join(f'{_int_count(severity_counts, sev)} {sev}' for sev in _SEVERITY_ORDER)
    scanners = ', '.join(_code_span(name) for name in scanner_names) if scanner_names else 'none'
    lines.append('## Scan summary')
    lines.append('')
    lines.append(f'- Repository: {_code_span(repo_name)}')
    lines.append(f'- Scanners: {scanners}')
    lines.append(f'- Findings: {totals} ({_int_count(severity_counts, "total")} total)')
    lines.append(f'- AI analysis: {"enabled" if ai_enabled else "not enabled"}')
    if gate is not None:
        verdict = 'passed' if gate.passed else 'did not pass'
        lines.append(f'- Policy gate: {verdict} (threshold: {_code_span(gate.threshold)})')
    else:
        lines.append('- Policy gate: not evaluated')
    lines.append('')

    # 3. Pin table (validated entries only, capped).
    lines.append('## Planned pins')
    lines.append('')
    valid_entries = [entry for entry in plan.entries if _entry_is_valid(entry)]
    excluded_count = len(plan.entries) - len(valid_entries)
    if valid_entries:
        lines.append('| Workflow | Line | Action | Old ref | Pinned SHA |')
        lines.append('| --- | --- | --- | --- | --- |')
        for entry in valid_entries[:_MAX_TABLE_ROWS]:
            lines.append(
                f'| {_code_span(entry.workflow_path)} | {int(entry.line_number)} '
                f'| {_code_span(entry.action_base, _MAX_REF_LEN)} '
                f'| {_code_span(entry.old_ref, _MAX_REF_LEN)} '
                f'| {_code_span(entry.new_sha, 40)} |'
            )
        overflow = len(valid_entries) - _MAX_TABLE_ROWS
        if overflow > 0:
            lines.append('')
            lines.append(f'... and {overflow} more (see diff)')
    else:
        lines.append('No actions were pinned.')
    if excluded_count > 0:
        lines.append('')
        lines.append(f'{excluded_count} entries excluded from this table (invalid reference format)')
    lines.append('')

    # 4. Not pinned (fixed reason strings only; never raw line content).
    lines.append('## Not pinned')
    lines.append('')
    if plan.skipped:
        for skipped in plan.skipped[:_MAX_SKIPPED_ROWS]:
            lines.append(
                f'- {_code_span(skipped.workflow_path)}:{int(skipped.line_number)} '
                f'— {_code_span(skipped.reason)}'
            )
        skipped_overflow = len(plan.skipped) - _MAX_SKIPPED_ROWS
        if skipped_overflow > 0:
            lines.append(f'- ... and {skipped_overflow} more (see scan report)')
    else:
        lines.append('Nothing was skipped.')
    lines.append('')

    # 5. Complementary hardening note.
    lines.append(
        "Note: GitHub's native workflow dependency lockfile (`gh actions-lock`) is a "
        'complementary hardening step — see '
        f'{_LOCKFILE_DOC_URL}'
    )
    lines.append('')

    # 6. Footer.
    lines.append('---')
    lines.append(f'Generated by ActChain {__version__}')

    return '\n'.join(lines)


