"""
Tests for the pinning PR module: hostile-input-safe body rendering and
Git-Data-API PR assembly against a fake PyGithub Repository.
"""

import base64
import re

import pytest
from github import GithubException, InputGitTreeElement

from actchain import __version__
from actchain.pinning import PinningPRError, create_pinning_pr, render_pr_body
from actchain.pipeline.context import GateResult, PinPlan, PinPlanEntry, SkippedPin

PATH = ".github/workflows/ci.yml"
SHA = "1234567890abcdef1234567890abcdef12345678"
BASE_SHA = "b" * 40


def entry(base="actions/checkout", old="v4", sha=SHA, path=PATH, line=4):
    return PinPlanEntry(workflow_path=path, line_number=line,
                        action_base=base, old_ref=old, new_sha=sha)


def body_for(plan, gate=None, stats=None, scanners=None, ai=False):
    return render_pr_body(
        plan,
        gate,
        stats or {"severity_counts": {"critical": 0, "high": 2, "medium": 1, "low": 3, "total": 6}},
        "owner/repo",
        scanners or ["zizmor", "opengrep"],
        ai,
    )


class TestRenderPrBody:
    def test_hostile_old_ref_is_excluded_and_counted(self):
        plan = PinPlan(entries=[
            entry(),
            entry(base="a/b", old="@victim #1 <img src=x>", line=9),
        ])
        body = body_for(plan)

        assert "@victim" not in body
        assert "<img" not in body
        assert "1 entries excluded from this table (invalid reference format)" in body
        # The legit entry still renders, every dynamic cell in a code span.
        assert f"| `{PATH}` | 4 | `actions/checkout` | `v4` | `{SHA}` |" in body

    def test_invalid_sha_is_excluded(self):
        plan = PinPlan(entries=[entry(sha="not-a-sha")])
        body = body_for(plan)
        assert "not-a-sha" not in body
        assert "1 entries excluded from this table (invalid reference format)" in body

    def test_valid_entries_have_no_exclusion_line(self):
        body = body_for(PinPlan(entries=[entry()]))
        assert "excluded from this table" not in body

    def test_hostile_workflow_path_cannot_escape_code_span(self):
        plan = PinPlan(entries=[entry(path="x`y|z.yml")])
        body = body_for(plan)
        assert "x`y" not in body  # backticks and pipes are stripped
        assert "`xyz.yml`" in body

    def test_table_capped_at_100_rows(self):
        plan = PinPlan(entries=[entry(line=i) for i in range(1, 102)])
        body = body_for(plan)
        assert body.count(f"| `{SHA}` |") == 100
        assert "... and 1 more (see diff)" in body

    def test_skipped_entries_listed_by_path_and_line_only(self):
        plan = PinPlan(skipped=[SkippedPin(PATH, 7, "no ref specified")])
        body = body_for(plan)
        assert f"- `{PATH}`:7 — `no ref specified`" in body

    def test_lockfile_note_and_link(self):
        body = body_for(PinPlan())
        assert "gh actions-lock" in body
        assert ("https://docs.github.com/en/actions/concepts/security/"
                "workflow-dependency-lockfiles") in body

    def test_summary_gate_and_footer(self):
        gate = GateResult(evaluated=True, passed=True, threshold="high")
        body = body_for(PinPlan(entries=[entry()]), gate=gate, ai=True)

        assert "# Pin GitHub Actions to commit SHAs" in body
        assert "- Repository: `owner/repo`" in body
        assert "`zizmor`" in body and "`opengrep`" in body
        assert "- Findings: 0 critical, 2 high, 1 medium, 3 low (6 total)" in body
        assert "- AI analysis: enabled" in body
        assert "- Policy gate: passed (threshold: `high`)" in body
        assert f"Generated by ActChain {__version__}" in body

    def test_ai_disabled_and_no_gate(self):
        body = body_for(PinPlan())
        assert "- AI analysis: not enabled" in body
        assert "- Policy gate: not evaluated" in body


