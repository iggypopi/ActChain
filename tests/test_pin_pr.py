class _Obj:
    """Attribute bag standing in for PyGithub response objects."""

    def __init__(self, **kwargs):
        self.__dict__.update(kwargs)


# Scan-time originals of the files make_plan() rewrites; FakeRepo serves
# these from get_contents by default, so verification passes.
ORIGINALS = {
    ".github/workflows/ci.yml": "ci original\n",
    ".github/workflows/build.yml": "build original\n",
}


class FakeRepo:
    """Offline PyGithub Repository double recording every Git Data call."""

    def __init__(self, reject_refs=0, fail_on=None, fail_status=403, base_files=None):
        self.default_branch = "main"
        self.reject_refs = reject_refs  # raise 422 for the first N create_git_ref calls
        self.fail_on = fail_on
        self.fail_status = fail_status
        self.base_files = dict(ORIGINALS) if base_files is None else base_files
        self.calls = []
        self._blob_counter = 0

    def _maybe_fail(self, name):
        if self.fail_on == name:
            raise GithubException(self.fail_status,
                                  {"message": "Resource not accessible by integration"})

    def get_git_ref(self, ref):
        self.calls.append(("get_git_ref", ref))
        self._maybe_fail("get_git_ref")
        assert ref == "heads/main"
        return _Obj(object=_Obj(sha=BASE_SHA))

    def get_git_commit(self, sha):
        self.calls.append(("get_git_commit", sha))
        return _Obj(sha=sha, tree=_Obj(sha="base-tree-sha"))

    def get_contents(self, path, ref=None):
        self.calls.append(("get_contents", path, ref))
        self._maybe_fail("get_contents")
        if path not in self.base_files:
            raise GithubException(404, {"message": "Not Found"})
        encoded = base64.b64encode(self.base_files[path].encode("utf-8")).decode("ascii")
        return _Obj(content=encoded, encoding="base64", sha=f"content-{path}", path=path)

    def create_git_blob(self, content, encoding):
        self.calls.append(("create_git_blob", content, encoding))
        self._blob_counter += 1
        return _Obj(sha=f"blob-{self._blob_counter}")

    def get_git_tree(self, sha):
        self.calls.append(("get_git_tree", sha))
        return _Obj(sha=sha)

    def create_git_tree(self, elements, base_tree):
        self.calls.append(("create_git_tree", elements, base_tree))
        return _Obj(sha="new-tree-sha")

    def create_git_commit(self, message, tree, parents):
        self.calls.append(("create_git_commit", message, tree, parents))
        return _Obj(sha="new-commit-sha")

    def create_git_ref(self, ref, sha):
        self.calls.append(("create_git_ref", ref, sha))
        self._maybe_fail("create_git_ref")
        if self.reject_refs > 0:
            self.reject_refs -= 1
            raise GithubException(422, {"message": "Reference already exists"})
        return _Obj(ref=ref)

    def create_pull(self, base, head, title, body):
        self.calls.append(("create_pull", base, head, title, body))
        self._maybe_fail("create_pull")
        return _Obj(html_url="https://github.com/owner/repo/pull/7")

    def named_calls(self, name):
        return [call for call in self.calls if call[0] == name]


class FakeClient:
    def __init__(self, repo):
        self.repo = repo


def make_plan():
    plan = PinPlan()
    plan.new_contents = {
        ".github/workflows/ci.yml": "ci rewritten\n",
        ".github/workflows/build.yml": "build rewritten\n",
    }
    plan.base_contents = dict(ORIGINALS)
    return plan


class TestCreatePinningPr:
    def test_happy_path_builds_on_recorded_base_sha(self):
        repo = FakeRepo()
        url = create_pinning_pr(FakeClient(repo), make_plan(), "title", "body")
        assert url == "https://github.com/owner/repo/pull/7"

        # Base recorded once and used for commit + tree (R8 TOCTOU).
        assert repo.named_calls("get_git_ref") == [("get_git_ref", "heads/main")]
        assert repo.named_calls("get_git_commit") == [("get_git_commit", BASE_SHA)]
        assert repo.named_calls("get_git_tree") == [("get_git_tree", "base-tree-sha")]

        # Every changed file verified against its scan-time content AT the
        # recorded base SHA before anything is written.
        assert repo.named_calls("get_contents") == [
            ("get_contents", ".github/workflows/build.yml", BASE_SHA),
            ("get_contents", ".github/workflows/ci.yml", BASE_SHA),
        ]

        # One blob per changed file, sorted by path, utf-8 encoded.
        blobs = repo.named_calls("create_git_blob")
        assert blobs == [("create_git_blob", "build rewritten\n", "utf-8"),
                         ("create_git_blob", "ci rewritten\n", "utf-8")]

        # Tree elements are real InputGitTreeElement blobs at mode 100644.
        (_, elements, base_tree), = repo.named_calls("create_git_tree")
        assert base_tree.sha == "base-tree-sha"
        assert all(isinstance(element, InputGitTreeElement) for element in elements)
        assert [element._identity for element in elements] == [
            {"path": ".github/workflows/build.yml", "mode": "100644", "type": "blob", "sha": "blob-1"},
            {"path": ".github/workflows/ci.yml", "mode": "100644", "type": "blob", "sha": "blob-2"},
        ]

        # Single commit on top of the recorded base commit.
        (_, message, tree, parents), = repo.named_calls("create_git_commit")
        assert message == "Pin GitHub Actions to commit SHAs\n\nGenerated by ActChain."
        assert tree.sha == "new-tree-sha"
        assert [parent.sha for parent in parents] == [BASE_SHA]

        # Branch created at the new commit with the refs/heads/ prefix.
        (_, ref, sha), = repo.named_calls("create_git_ref")
        assert re.fullmatch(r"refs/heads/actchain/pin-actions-\d{14}", ref)
        assert sha == "new-commit-sha"

        # PR opened from that branch against the default branch.
        (_, base, head, title, body), = repo.named_calls("create_pull")
        assert base == "main"
        assert ref == f"refs/heads/{head}"
        assert (title, body) == ("title", "body")

    def test_existing_branch_retries_with_suffix(self):
        repo = FakeRepo(reject_refs=1)
        create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")

        refs = [call[1] for call in repo.named_calls("create_git_ref")]
        assert len(refs) == 2
        assert refs[1] == f"{refs[0]}-2"
        (_, _, head, _, _), = repo.named_calls("create_pull")
        assert head.endswith("-2")

    def test_gives_up_after_five_branch_attempts(self):
        repo = FakeRepo(reject_refs=5)
        with pytest.raises(PinningPRError, match="unique branch"):
            create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")
        assert repo.named_calls("create_pull") == []

    def test_changed_file_since_scan_aborts_before_any_write(self):
        base_files = dict(ORIGINALS)
        base_files[".github/workflows/ci.yml"] = "tampered after scan\n"
        repo = FakeRepo(base_files=base_files)

        with pytest.raises(PinningPRError, match="changed since the scan"):
            create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")

        assert repo.named_calls("create_git_blob") == []
        assert repo.named_calls("create_git_ref") == []
        assert repo.named_calls("create_pull") == []

    def test_file_deleted_since_scan_counts_as_changed(self):
        repo = FakeRepo(base_files={
            ".github/workflows/build.yml": ORIGINALS[".github/workflows/build.yml"],
        })  # ci.yml missing at the base SHA -> 404

        with pytest.raises(PinningPRError, match="changed since the scan"):
            create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")

        assert repo.named_calls("create_git_ref") == []
        assert repo.named_calls("create_pull") == []

    def test_verification_fetch_error_maps_to_pr_error(self):
        repo = FakeRepo(fail_on="get_contents", fail_status=403)
        with pytest.raises(PinningPRError, match="verifying workflow files"):
            create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")
        assert repo.named_calls("create_pull") == []

    def test_403_maps_to_error_with_permissions_hint(self):
        repo = FakeRepo(fail_on="create_git_ref", fail_status=403)
        with pytest.raises(PinningPRError) as excinfo:
            create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")
        message = str(excinfo.value)
        assert "403" in message
        assert ("the token needs contents:write and pull-requests:write "
                "permissions on the repository") in message

    def test_404_on_create_pull_gets_permissions_hint(self):
        repo = FakeRepo(fail_on="create_pull", fail_status=404)
        with pytest.raises(PinningPRError, match="pull-requests:write"):
            create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")

    def test_other_statuses_map_without_hint(self):
        repo = FakeRepo(fail_on="get_git_ref", fail_status=500)
        with pytest.raises(PinningPRError) as excinfo:
            create_pinning_pr(FakeClient(repo), make_plan(), "t", "b")
        message = str(excinfo.value)
        assert "500" in message
        assert "contents:write" not in message

    def test_empty_plan_is_an_error(self):
        with pytest.raises(PinningPRError, match="no file changes"):
            create_pinning_pr(FakeClient(FakeRepo()), PinPlan(), "t", "b")
